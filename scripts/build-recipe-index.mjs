// Regenerates src/content/recipes/index.ts from the frontmatter of every
// recipe markdown file, and mirrors each file to public/recipes for download.
// Runs automatically before `dev` and `build`. Add a recipe by dropping a .md
// file with frontmatter into src/content/recipes, nothing else to edit.
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const root = process.cwd();
const srcDir = path.join(root, "src/content/recipes");
const pubDir = path.join(root, "public/recipes");
const CATEGORY_ORDER = ["Bread", "Breakfast", "Dinner", "Dessert", "Pantry"];

fs.mkdirSync(pubDir, { recursive: true });

const recipes = fs
  .readdirSync(srcDir)
  .filter((f) => f.endsWith(".md"))
  .map((file) => {
    const raw = fs.readFileSync(path.join(srcDir, file), "utf8");
    const { data } = matter(raw);
    const slug = file.replace(/\.md$/, "");
    const pubPath = path.join(pubDir, file);
    if (!fs.existsSync(pubPath) || fs.readFileSync(pubPath, "utf8") !== raw) {
      fs.writeFileSync(pubPath, raw);
    }
    return {
      slug,
      title: String(data.title ?? slug),
      subtitle: String(data.subtitle ?? ""),
      yield: String(data.yield ?? ""),
      totalTime: String(data.total_time ?? ""),
      tags: Array.isArray(data.tags) ? data.tags.map(String) : [],
      category: String(data.category ?? "Dinner"),
      source: String(data.source ?? "Kitchen notebook"),
      updated: data.updated instanceof Date ? data.updated.toISOString().slice(0, 10) : String(data.updated ?? ""),
      filePath: `recipes/${file}`,
    };
  })
  .sort((a, b) => {
    const c = CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category);
    return c !== 0 ? c : a.title.localeCompare(b.title);
  });

const out = `// ============================================================================
// RECIPE INDEX (generated by scripts/build-recipe-index.mjs, do not edit)
// ============================================================================

export type RecipeCategory = ${CATEGORY_ORDER.map((c) => JSON.stringify(c)).join(" | ")};

export interface RecipeMeta {
  slug: string;
  title: string;
  subtitle: string;
  yield: string;
  totalTime: string;
  tags: string[];
  category: RecipeCategory;
  source: string;
  updated: string;
  filePath: string;
  /** Optional photo path, e.g. "/recipes/photos/city-loaf.jpg". */
  image?: string;
}

export const RECIPE_CATEGORIES: RecipeCategory[] = ${JSON.stringify(CATEGORY_ORDER)};

export const recipes: RecipeMeta[] = ${JSON.stringify(recipes, null, 2)};

export function getRecipeBySlug(slug: string): RecipeMeta | undefined {
  return recipes.find((r) => r.slug === slug);
}
`;

const indexPath = path.join(srcDir, "index.ts");
const tmp = indexPath + ".tmp";
fs.writeFileSync(tmp, out);
fs.renameSync(tmp, indexPath);
console.log(`recipes: indexed ${recipes.length}`);
